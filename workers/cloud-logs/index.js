function textResponse(message, status = 200) {
  return new Response(message, {
    status,
    headers: {
      ...CORS_HEADERS,
      "Content-Type": "text/plain; charset=utf-8",
      "Cache-Control": "no-store",
      "X-Content-Type-Options": "nosniff",
    },
  });
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (request.method === "OPTIONS") {
      return new Response(null, { headers: CORS_HEADERS });
    }

    const sessionId = url.searchParams.get("session");
    if (!sessionId || !SESSION_ID_RE.test(sessionId)) {
      return textResponse("ID de sessão ausente ou inválido (?session=ID)", 400);
    }

    if (url.pathname === "/view" && request.method === "GET") {
      return new Response(renderView(sessionId), {
        headers: {
          "Content-Type": "text/html; charset=utf-8",
          "Cache-Control": "no-store",
          "X-Content-Type-Options": "nosniff",
          "Referrer-Policy": "no-referrer",
          "Content-Security-Policy": "default-src 'none'; img-src data:; style-src 'unsafe-inline'; script-src 'unsafe-inline'; connect-src 'self'; base-uri 'none'; frame-ancestors 'none'",
        },
      });
    }

    if ((url.pathname === "/push" && request.method === "POST")
      || (url.pathname === "/stream" && request.method === "GET")) {
      const id = env.SESSION_LOG.idFromName(sessionId);
      return env.SESSION_LOG.get(id).fetch(request);
    }

    return textResponse("Rota não encontrada", 404);
  },
};

// Keep the Durable Object class name and storage key unchanged so the existing
// SESSION_LOG binding and stored sessions continue to work after deployment.
export class SessionLog {
  constructor(state) {
    this.state = state;
    this.clients = new Set();
    this.logs = [];
    this.ready = this.state.blockConcurrencyWhile(async () => {
      this.logs = await this.state.storage.get("logs") || [];
    });
  }

  async fetch(request) {
    await this.ready;
    const url = new URL(request.url);

    if (url.pathname === "/push" && request.method === "POST") {
      let data;
      try {
        data = await request.json();
      } catch {
        return textResponse("JSON inválido", 400);
      }

      if (typeof data?.message !== "string") {
        return textResponse("Campo 'message' ausente", 400);
      }

      const entry = {
        message: data.message.slice(0, 16_000),
        percent: Number.isFinite(data.percent) ? Math.max(-1, Math.min(100, data.percent)) : -1,
        ts: Date.now(),
      };

      this.logs.push(entry);
      if (this.logs.length > MAX_LOGS_PER_SESSION) this.logs.shift();
      await this.state.storage.put("logs", this.logs);

      const encoded = new TextEncoder().encode(`data: ${JSON.stringify(entry)}\n\n`);
      for (const controller of this.clients) {
        try {
          controller.enqueue(encoded);
        } catch {
          this.clients.delete(controller);
        }
      }

      return textResponse("OK");
    }

    if (url.pathname === "/stream" && request.method === "GET") {
      const encoder = new TextEncoder();
      let heartbeat;
      let clientController;
      const body = new ReadableStream({
        start: (controller) => {
          clientController = controller;
          this.clients.add(controller);
          for (const log of this.logs) {
            controller.enqueue(encoder.encode(`data: ${JSON.stringify(log)}\n\n`));
          }
          heartbeat = setInterval(() => {
            try {
              controller.enqueue(encoder.encode(": ping\n\n"));
            } catch {
              clearInterval(heartbeat);
              this.clients.delete(controller);
            }
          }, HEARTBEAT_INTERVAL_MS);
        },
        cancel: () => {
          clearInterval(heartbeat);
          if (clientController) this.clients.delete(clientController);
        },
      });

      return new Response(body, {
        headers: {
          ...CORS_HEADERS,
          "Content-Type": "text/event-stream; charset=utf-8",
          "Cache-Control": "no-cache, no-transform",
          Connection: "keep-alive",
          "X-Accel-Buffering": "no",
        },
      });
    }

    return textResponse("Rota não encontrada", 404);
  }
}

